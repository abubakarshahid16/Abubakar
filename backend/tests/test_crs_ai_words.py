def test_plain_removes_ids_and_codes_and_drops_a_sentence_that_still_holds_a_code_word():
    got = words.plain(
        "Provide S-EQ-04 as sheet_silent says. The gate refused it. Give the value."
    )
    assert (
        got == "Provide as the AI reviewer found the paper silent says. Give the value."
    )
    assert words.plain("The guard said so.") == ""


def test_the_priority_rule_as_stated():
    rule = {"source": "rule"}
    advice = {"source": "rule", "rule_kind": "advice"}
    check = {"source": "skill"}
    assert words.priority("Fail", check) == "High"
    assert words.priority("AI opinion", rule, words.ORDER_AI_NOT_MET) == "High"
    assert words.priority("AI opinion", advice, words.ORDER_AI_NOT_MET) == "Medium"
    assert words.priority("AI opinion", check, words.ORDER_AI_NOT_MET) == "Medium"
    assert words.priority("AI opinion", rule, words.ORDER_AI_MET) == ""
    assert (
        words.priority("Query", rule) == "Medium"
        and words.priority("Query", advice) == "Low"
    )
    assert words.priority("Query", check) == "Low"
    assert words.priority("Pass", rule) == ""


def test_comment_by_and_the_generated_by_sentence():
    assert words.comment_by("instrument") == "AI reviewer, instrument"
    assert (
        words.comment_by("") == "AI reviewer"
        and words.comment_by(None) == "AI reviewer"
    )
    assert (
        words.generated_by("")
        == "Generated by AI, to be confirmed by a COMPANY engineer"
    )
    assert (
        words.generated_by("Acme")
        == "Generated by AI, to be confirmed by a Acme engineer"
    )


def _db():
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    conn.execute(
        "CREATE TABLE document_classification (document_id TEXT, project TEXT, document_number TEXT, title TEXT, revision TEXT,"
        " effective_date TEXT, discipline TEXT, discipline_canonical TEXT, equipment_type TEXT)"
    )
    return conn


def test_the_header_facts_are_what_the_app_holds_and_blank_otherwise():
    conn = _db()
    conn.execute(
        "INSERT INTO document_classification VALUES ('d1','P','N-1','T','B','2026-02-03','Cover words','instrument',NULL)"
    )
    conn.execute(
        "INSERT INTO document_classification VALUES ('d2',NULL,NULL,NULL,NULL,NULL,NULL,NULL,'pressure_relief_valve')"
    )
    assert header.document_header(conn, "d1") == {
        "project": "P", "document_number": "N-1", "title": "T", "revision": "B", "date": "2026-02-03",
        "discipline": "instrument",
    }  # fmt: skip
    second = header.document_header(conn, "d2", "pressure_relief_valve")
    assert (
        header.document_header(conn, "d2")["discipline"] == ""
    )  # a stored equipment type is not read on its own
    assert (
        second["discipline"] == "pressure relief valve"
        and second["project"] == ""
        and second["revision"] == ""
    )
    assert header.document_header(conn, "nobody") == dict.fromkeys(header.FIELDS, "")
    assert (
        header.document_header(conn, "nobody", "safety_valve")["discipline"]
        == "safety valve"
    )


