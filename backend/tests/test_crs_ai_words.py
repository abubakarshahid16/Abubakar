def test_every_guard_reason_constant_has_a_plain_phrase_and_none_holds_a_code_word():
    """Collects every `*_WHY` constant of the verdict module and every absence reason: each prints as a phrase, never raw."""
    constants = {
        v
        for k, v in vars(V).items()
        if k.endswith("_WHY") and isinstance(v, str) and not k.startswith("CLASS_")
    }
    constants |= set(absence.ABSENCE_WHY.values())
    assert len(constants) >= 20
    for text in constants:
        phrase = words.why_phrase(text)
        assert phrase and phrase != words.UNKNOWN_WHY, text
        assert not words.has_banned(phrase), phrase


def test_every_absence_code_is_in_the_table():
    assert set(words.ABSENCE_PLAIN) == set(absence.ABSENCE_WHY)


def test_an_unknown_reason_is_never_printed_raw():
    assert words.why_phrase("zz_internal_state_17 blew up") == words.UNKNOWN_WHY
    assert words.why_phrase("") == ""


def test_a_reason_of_several_parts_is_joined_in_plain_words():
    got = words.why_phrase(V.SILENCE_WHY + "; the rule is also not AI approved: values")
    assert (
        got == f"{words.WHY_PHRASES[V.SILENCE_WHY]}; the rule has not been approved yet"
    )


