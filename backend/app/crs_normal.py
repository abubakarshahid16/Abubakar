"""The normal reviewer's CRS in the app's one layout (order 13, part B).

`crs_export.build_crs_view` still decides what the sheet SAYS (the rows, their order, their numbers, their comment texts); this module
only moves it into the one layout: sheet "CRS" with the ten columns Item No, Document Name, Page No./Section, COMPANY Comments, Comment
By, Contractor's Response, Final Resolution, Standard Reference, Priority, Status; the header block; (internal copy) a sheet "Evidence"
for what the old extra columns held (rank word, reference, AI review comment, reasoning, rule trust) and a sheet "Notes" (the priority
rule, the verdict -> Status mapping, counts per Status equal to the rows). The issue copy to the contractor carries neither sheet and not
the "Generated by AI" sentence: it holds engineer-confirmed comments only.

Status: `crs_mapping.crs_status` (Pass or Fail only when its code path proved it). Priority: the AI reviewer's stated rule
(`crs_ai_words.priority`); a normal row stores no shall/must flag, so it counts as not mandatory: Fail High, AI opinion Medium,
Query Low, Pass blank.
"""

from __future__ import annotations

from . import crs_ai_header, crs_layout
from . import crs_ai_words as words
from .crs_mapping import crs_status

EVIDENCE_COLUMNS = (
    "Item No", "Status", "Row kind", "Rank (old Priority word)", "Reference", "AI Review Comments", "Reasoning (internal)",
    "Rule trust (internal)",
)  # fmt: skip
EVIDENCE_WIDTHS = (9.0, 13.0, 24.0, 22.0, 14.0, 60.0, 70.0, 28.0)
STATUS_MAPPING = (
    "Fail = a figure its code compared and found out of limit (rank 'Out of limit'). Pass = a safety tick: a compliant verdict its "
    "code reached through a safety-tier rule, for the engineer to tick. AI opinion = an AI engineering check, clause review, spec "
    "kit item or web standard check (a draft until an engineer confirms). Query = every other row; nothing is proven."
)


def _header_facts(meta: dict) -> dict:
    """The document's facts: `meta['header']`, else read for the run (blank when the run or the paper is not found)."""
    if isinstance(meta.get("header"), dict):
        return meta["header"]
    from .db import connect

    run = meta.get("review_run_id")
    return crs_ai_header.header_for_run(connect(), run) if run else {}


def _pairs(view: dict, meta: dict) -> list[tuple[str, str]]:
    h = _header_facts(meta)
    old = {p["label"]: p["value"] for p in view["header"]}
    applied = [
        s["standard"] for s in view["applicable_standards"] if s["status"] == "Applied"
    ]
    pairs = [
        ("Project:", h.get("project", "")),
        ("Document number:", h.get("document_number", "")),
        ("Document title:", h.get("title") or old.get("Document Title:", "")),
        ("Revision:", h.get("revision", "")),
        ("Date:", h.get("date", "")),
        ("Discipline:", h.get("discipline", "")),
        ("Rule books used:", "; ".join(applied)),
    ]
    pairs += [(k, v) for k, v in old.items() if k != "Document Title:"]
    pairs += (
        [("Review status:", view["run_status_note"])] if view["run_status_note"] else []
    )
    pairs += (
        [("Not fully checked:", view["incomplete_notice"])]
        if view["incomplete_notice"]
        else []
    )
    if view["recommended_code"]:
        reason = (
            f" - {view['recommended_code_reason']}"
            if view["recommended_code_reason"]
            else ""
        )
        pairs.append(
            (view["recommended_code_label"], f"{view['recommended_code']}{reason}")
        )
        pairs += (
            [("", view["recommended_code_status"])]
            if view["recommended_code_status"]
            else []
        )
    pairs += (
        [("Rule book version 2:", view["rulebook_v2_note"])]
        if view["rulebook_v2_note"]
        else []
    )
    return pairs


def _status_and_priority(entry: dict) -> tuple[str, str]:
    status = crs_status(entry.get("row_kind"), entry.get("priority"))
    return status, words.priority(status, {}, words.ORDER_AI_NOT_MET)


def layout_view(view: dict, meta: dict) -> dict:
    """The view of `crs_export.build_crs_view` as plain values for `crs_layout.layout_workbook`."""
    internal = view["crs_copy"] == "internal"
    marks = [_status_and_priority(e) for e in view["rows"]]
    rows = [
        [e["item_no"], e["document_name"], e["page_section"], e["comment"], e["comment_by"], e["contractor_response"],
         e["final_resolution"], e["standard_reference"], pri or None, status]
        for e, (status, pri) in zip(view["rows"], marks, strict=True)
    ]  # fmt: skip
    out = {
        "title": view["title"],
        "header": _pairs(view, meta),
        "sentence": words.generated_by(meta.get("company_name", ""))
        if internal
        else "",
        "rows": rows,
        "statuses": [s for s, _p in marks],
    }
    if internal:
        out["evidence"] = {
            "columns": EVIDENCE_COLUMNS,
            "statuses": [s for s, _p in marks],
            "widths": EVIDENCE_WIDTHS,
            "rows": [
                [e["item_no"], s, e["row_kind"], e.get("priority_label") or None, e["row_ref"],
                 e["ai_review_comment"] or None, e["reasoning"] or None, e["rule_trust"] or None]
                for e, (s, _p) in zip(view["rows"], marks, strict=True)
            ],
        }  # fmt: skip
        counts = [
            (f"Count: {s}", sum(1 for m, _p in marks if m == s)) for s in words.STATUSES
        ]
        out["notes"] = {
            "columns": ("Topic", "Detail"),
            "widths": (44.0, 120.0),
            "rows": [
                ["Priority rule", words.PRIORITY_RULE],
                ["Status mapping", STATUS_MAPPING],
                *[list(c) for c in counts],
                ["Count: rows on the CRS sheet", len(rows)],
            ],
        }
    return out


def workbook(view: dict, meta: dict):
    """The normal reviewer's workbook in the one layout, with the reply tip on every Contractor's Response cell."""
    from openpyxl.worksheet.datavalidation import DataValidation

    from . import crs_export as ce

    wb = crs_layout.layout_workbook(layout_view(view, meta))
    ws = wb["CRS"]
    if view["rows"]:
        top = next(
            r for r in range(1, ws.max_row + 1) if ws.cell(r, 1).value == "Item No"
        )
        tip = DataValidation(
            type="textLength", operator="greaterThanOrEqual", formula1="0", allow_blank=True, showErrorMessage=False,
            showInputMessage=True, promptTitle=ce.RESPONSE_PROMPT_TITLE, prompt=ce.RESPONSE_PROMPT,
        )  # fmt: skip
        tip.add(f"F{top + 1}:F{top + len(view['rows'])}")
        ws.add_data_validation(tip)
    return wb
