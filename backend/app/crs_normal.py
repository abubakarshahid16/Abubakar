"""The normal reviewer's CRS in the app's one layout (order 13, part B).

`crs_export.build_crs_view` still decides what the sheet SAYS (the rows, their order, their numbers, their comment texts); this module
only moves it into the one layout: sheet "CRS" with the ten columns Item No, Document Name, Page No./Section, COMPANY Comments, Comment
By, Contractor's Response, Final Resolution, Standard Reference, Priority, Status; the header block; (internal copy) a sheet "Evidence"
for what the old extra columns held (rank word, reference, AI review comment, reasoning, rule trust) and a sheet "Notes" (the priority
rule, the verdict -> Status mapping, counts per Status equal to the rows). The issue copy to the contractor carries neither sheet and not
the "Generated by AI" sentence: it holds engineer-confirmed comments only.

Status: `crs_status` below, from the row's own kind and rank: Fail = rank 1 "Out of limit" (a figure its code compared and found out of
limit); Pass = a safety tick (a compliant verdict its code reached through a safety-tier rule; the engineer still ticks it); AI opinion =
an AI engineering check, clause review, spec kit item or web standard check (a draft until an engineer confirms); Query = every other
row (missing value, needs engineer review, another document, not cited, engineer's comment, carried forward, pages not readable). Priority: the AI reviewer's stated rule
(`crs_ai_words.priority`); a normal row stores no shall/must flag, so it counts as not mandatory: Fail High, AI opinion Medium,
Query Low, Pass blank.
"""

from __future__ import annotations

from . import crs_ai_words as words
from . import crs_export as ce
from . import crs_export_quality as quality
from . import crs_layout
from .crs_ai_words import STATUS_AI, STATUS_FAIL, STATUS_PASS, STATUS_QUERY
from .crs_mapping import (
    PRIORITY_OUT_OF_LIMIT,
    ROW_KIND_AI_ENGINEERING_CHECK,
    ROW_KIND_DATASHEET_CHECK,
    ROW_KIND_NON_COMPLIANT,
    ROW_KIND_SAFETY_TICK,
    ROW_KIND_WEB_STANDARD_CHECK,
)

EVIDENCE_COLUMNS = (
    "Item No", "Status", "Row kind", "Rank (old Priority word)", "Reference", "AI Review Comments", "Reasoning (internal)",
    "Rule trust (internal)",
)  # fmt: skip
EVIDENCE_WIDTHS = (9.0, 13.0, 24.0, 22.0, 14.0, 60.0, 70.0, 28.0)
STATUS_MAPPING = (
    "Fail = a figure its code compared and found out of limit (rank 'Out of limit'). Pass = a safety tick: a compliant verdict its "
    "code reached through a safety-tier rule, for the engineer to tick. AI opinion = an AI engineering check, clause review, spec "
    "kit item or web standard check (a draft until an engineer confirms). Query = every other row; nothing is proven."
)


_AI_ROW_KINDS = frozenset(
    {
        ROW_KIND_AI_ENGINEERING_CHECK,
        ROW_KIND_WEB_STANDARD_CHECK,
        "clause_review",
        "spec_kit",
    }
)


#: The kinds whose rank 1 ("Out of limit") is a figure its code compared: the ONLY kinds that can be a Fail. (A rank copied onto a row of
#: another kind, or a kind this table does not know, is never a Fail.)
CODE_COMPARED_KINDS = frozenset({ROW_KIND_NON_COMPLIANT, ROW_KIND_DATASHEET_CHECK})


def crs_status(row_kind: str | None, priority: int | None) -> str:
    """The Status word of one normal-reviewer row, from its OWN verdict fields (the table in the module docstring). Never a Pass or a
    Fail that its code path did not prove; a kind it does not know is a Query at every rank."""
    if row_kind in _AI_ROW_KINDS:
        return STATUS_AI
    if row_kind == ROW_KIND_SAFETY_TICK:
        return STATUS_PASS
    if row_kind in CODE_COMPARED_KINDS and priority == PRIORITY_OUT_OF_LIMIT:
        return STATUS_FAIL
    return STATUS_QUERY


def _pairs(view: dict, meta: dict) -> list[tuple[str, str]]:
    h = (
        meta.get("header") or {}
    )  # supplied by the caller (`export_status.header_facts`); this module reads no database
    old = {p["label"]: p["value"] for p in view["header"]}
    applied = [
        s["standard"] for s in view["applicable_standards"] if s["status"] == "Applied"
    ]
    pairs = [
        ("Project:", h.get("project", "")),
        ("Document number:", h.get("document_number", "")),
        (
            "Document title:",
            old.get("Document Title:") or h.get("title", ""),
        ),  # what it showed before: the file name
        ("Revision:", h.get("revision", "")),
        ("Date:", h.get("date", "")),
        ("Discipline:", h.get("discipline", "")),
        ("Rule books used:", "; ".join(applied)),
    ]
    pairs += [(k, v) for k, v in old.items() if k != "Document Title:"]
    return pairs


def _below(view: dict) -> list[tuple[int, str, str, int]]:
    """What stood under the table before and still does: the incomplete-review notice, the review code with its reason and status,
    the rule book version 2 note (offsets from the last table row, as before)."""
    out = (
        [(1, "", view["incomplete_notice"], 1, quality.notice_height(view))]
        if view["incomplete_notice"]
        else []
    )
    if view["recommended_code"]:
        reason = (
            f" - {view['recommended_code_reason']}"
            if view["recommended_code_reason"]
            else ""
        )
        out.append(
            (
                2,
                view["recommended_code_label"],
                f"{view['recommended_code']}{reason}",
                3,
            )
        )
        out += (
            [(3, "", view["recommended_code_status"], 3)]
            if view["recommended_code_status"]
            else []
        )
    return out + (
        [(4, "", view["rulebook_v2_note"], 3)] if view["rulebook_v2_note"] else []
    )


def decorate(view: dict, meta: dict) -> dict:
    """THE one row model of the file and the preview: every row gets its Status and the Priority word of its copy; the INTERNAL view's
    columns are the one layout's ten and its header the one layout's facts. A contractor-facing (issue) view keeps its nine company
    columns, its own header and its own Priority words, and no Status (it would say which comments were drafts)."""
    internal = view["crs_copy"] == "internal"
    for row in view["rows"]:
        status = crs_status(row.get("row_kind"), row.get("priority"))
        row["rank_word"] = row[
            "priority_label"
        ]  # the old word, kept for the Evidence sheet
        row["status"] = status if internal else ""
        # ONE vocabulary: both copies of one review print the same Priority word for a row (the stated rule, one function)
        row["priority_label"] = words.priority(status, {}, words.ORDER_AI_NOT_MET)
    overflow = (
        ce.AI_COLUMN in view["columns"] and not internal
    )  # a long issued comment's overflow stays on the sheet
    view["columns"] = list(
        crs_layout.LAYOUT_COLUMNS if internal else crs_layout.LAYOUT_COLUMNS[:9]
    )
    if overflow:
        view["columns"].append(ce.AI_COLUMN)
    if internal:
        view["header"] = [{"label": k, "value": v} for k, v in _pairs(view, meta)]
    return view


def row_cells(entry: dict) -> tuple[list, str]:
    """One row's cells in the one layout's order (ten with Status on the internal copy, nine on a contractor-facing one), and its Status."""
    cells = [
        entry["item_no"], entry["document_name"], entry["page_section"], entry["comment"], entry["comment_by"],
        entry["contractor_response"], entry["final_resolution"], entry["standard_reference"], entry["priority_label"] or None,
    ]  # fmt: skip
    return ([*cells, entry["status"]] if entry["status"] else cells), entry["status"]


def _cells_of(entry: dict, columns: list) -> list:
    cells, _s = row_cells(entry)
    return (
        [*cells, entry["ai_review_comment"] or None]
        if ce.AI_COLUMN in columns
        else cells
    )


def layout_view(view: dict, meta: dict) -> dict:
    """The (decorated) view of `crs_export.build_crs_view` as plain values for `crs_layout.layout_workbook`."""
    internal = view["crs_copy"] == "internal"
    rows = [_cells_of(e, view["columns"]) for e in view["rows"]]
    statuses = [e["status"] for e in view["rows"]]
    out = {
        "title": "\n".join(p for p in (view["run_status_note"], view["title"]) if p),
        "title_height": 75 if view["run_status_note"] else None,
        "below": _below(view),
        "row_heights": [ce.row_height(e["comment"]) for e in view["rows"]],
        "header": [(h["label"], h["value"]) for h in view["header"]],
        "columns": view["columns"],
        "widths": (*crs_layout.LAYOUT_WIDTHS[:9], 60.0)
        if ce.AI_COLUMN in view["columns"]
        else None,
        "plain": not internal,
        "gap": 1 if internal else 0,
        "rows": rows,
        "statuses": statuses,
    }
    if internal:
        out["sentence"] = words.generated_by(meta.get("company_name", ""))
        out["evidence"] = {
            "columns": EVIDENCE_COLUMNS,
            "statuses": statuses,
            "widths": EVIDENCE_WIDTHS,
            "rows": [
                [e["item_no"], e["status"], e["row_kind"], e.get("rank_word") or None, e["row_ref"],
                 e["ai_review_comment"] or None, e["reasoning"] or None, e["rule_trust"] or None]
                for e in view["rows"]
            ],
        }  # fmt: skip
        counts = [(f"Count: {s}", statuses.count(s)) for s in words.STATUSES]
        out["notes"] = {
            "columns": ("Topic", "Detail"),
            "widths": (44.0, 120.0),
            "rows": [
                ["Priority rule", words.PRIORITY_RULE],
                ["Status mapping", STATUS_MAPPING],
                *[list(c) for c in counts],
                ["Count: rows on the CRS sheet", len(rows)],
            ],
        }
    return out


def workbook(view: dict, meta: dict):
    """The normal reviewer's workbook in the one layout, with the reply tip on every Contractor's Response cell."""
    from openpyxl.worksheet.datavalidation import DataValidation

    wb = crs_layout.layout_workbook(layout_view(view, meta))
    ws = wb["CRS"]
    if view["rows"]:
        top = next(
            r for r in range(1, ws.max_row + 1) if ws.cell(r, 1).value == "Item No"
        )
        tip = DataValidation(
            type="textLength", operator="greaterThanOrEqual", formula1="0", allow_blank=True, showErrorMessage=False,
            showInputMessage=True, promptTitle=ce.RESPONSE_PROMPT_TITLE, prompt=ce.RESPONSE_PROMPT,
        )  # fmt: skip
        tip.add(f"F{top + 1}:F{top + len(view['rows'])}")
        ws.add_data_validation(tip)
    return wb
