"""Build `.github/client-data-hashes.txt`, the list `check_client_identifiers.py` reads.

Run on the owner's machine only. The inputs stay outside the repository; only keyed
hashes are written, so the tracked list does not spell a name or a sentence:

* `--tokens FILE`: the real names, document numbers, filenames and tags, one per line
  (`#` starts a comment);
* `--db COPY`: a READ-ONLY copy of the database (`?immutable=1`, never the live file).
  Every document that is not a company standard gives its filename, document number,
  equipment tags and all its 8-word runs. Runs also found in a company standard are
  dropped: public standards' numbers and wording must never be blocked. So are runs
  with fewer than three real words, which are only numbers.
* `--allow FILE` (optional): phrases reviewed as generic English that also happen to be
  in a client document; their runs are not listed.

    python scripts/build_client_data_list.py --tokens <file> --db <copy> [--allow <file>]
"""

from __future__ import annotations

import argparse
import json
import secrets
import sqlite3
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import check_client_identifiers as guard  # noqa: E402

NGRAM = guard.NGRAM_WORDS
MIN_REAL_WORDS = 3


def words_of(text: str) -> list[str]:
    return [word for word, _ in guard.normalized_words(text)]


def runs(words: list[str], size: int = NGRAM) -> set[tuple[str, ...]]:
    return {tuple(words[i : i + size]) for i in range(len(words) - size + 1)}


def _is_wording(run: tuple[str, ...]) -> bool:
    return sum(1 for word in run if word.isalpha() and len(word) > 1) >= MIN_REAL_WORDS


def read_copy(
    db_path: Path,
) -> tuple[list[str], set[tuple[str, ...]], set[tuple[str, ...]]]:
    """(identifying strings, client runs, standards' runs) from a read-only copy."""
    conn = sqlite3.connect(f"file:{db_path}?mode=ro&immutable=1", uri=True)
    role = "coalesce(c.document_role, '')"
    join = "documents d left join document_classification c on c.document_id = d.id"
    tokens: list[str] = []
    for filename, number, tags in conn.execute(
        f"select d.filename, c.document_number, c.equipment_tags from {join} "
        f"where {role} <> 'COMPANY_STANDARD'"
    ):
        tokens += [t for t in (filename, number) if t]
        tokens += json.loads(tags) if tags else []
    page_sql = (
        "select p.text from pages p join documents d on p.document_id = d.id "
        f"left join document_classification c on c.document_id = d.id where {role} "
    )
    client: set[tuple[str, ...]] = set()
    for (text,) in conn.execute(page_sql + "<> 'COMPANY_STANDARD'"):
        client |= runs(words_of(text or ""))
    standards: set[tuple[str, ...]] = set()
    for (text,) in conn.execute(page_sql + "= 'COMPANY_STANDARD'"):
        standards |= runs(words_of(text or ""))
    conn.close()
    return tokens, client, standards


def build(
    tokens: list[str],
    client_runs: set[tuple[str, ...]],
    standard_runs: set[tuple[str, ...]],
    allow_runs: set[tuple[str, ...]],
    salt: bytes,
) -> tuple[list[int], list[str]]:
    """(lengths to scan, sorted digests). The heart of the list, free of files."""
    listed = {tuple(w) for w in map(words_of, tokens) if w}
    listed |= {r for r in client_runs - standard_runs - allow_runs if _is_wording(r)}
    lengths = sorted({len(r) for r in listed})
    return lengths, sorted({guard.digest(salt, list(r)) for r in listed})


def _lines(path: Path | None) -> list[str]:
    if not path:
        return []
    found = (ln.split("#", 1)[0].strip() for ln in path.read_text("utf-8").splitlines())
    return [ln for ln in found if ln]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tokens", type=Path, required=True)
    ap.add_argument("--db", type=Path, required=True)
    ap.add_argument("--allow", type=Path)
    ap.add_argument("--out", type=Path, default=REPO / guard.HASH_FILE)
    args = ap.parse_args(argv)
    from_db, client, standards = read_copy(args.db)
    tokens = _lines(args.tokens) + from_db
    allow: set[tuple[str, ...]] = set()
    for phrase in _lines(args.allow):
        allow |= runs(words_of(phrase))
    # The salt stays across rebuilds: the exception file's digests depend on it.
    old = args.out.read_text("utf-8").splitlines()[2:3] if args.out.is_file() else []
    salt = bytes.fromhex(old[0].split()[1]) if old else secrets.token_bytes(16)
    lengths, digests = build(tokens, client, standards, allow, salt)
    head = [
        "# Keyed hashes of client data for scripts/check_client_identifiers.py.",
        "# Generated by scripts/build_client_data_list.py; do not edit by hand.",
        f"salt {salt.hex()}",
        "lengths " + " ".join(map(str, lengths)),
    ]
    args.out.write_text("\n".join(head + digests) + "\n", encoding="utf-8")
    print(f"{len(digests)} entries, lengths {lengths} -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
